#!/usr/bin/env node
/**
 * generate-commercial-pages.mjs — /commercial/<slug>/ landing pages, one per
 * commercial property type, from data/commercial-types.json.
 *
 *   node scripts/generate-commercial-pages.mjs
 *
 * The nav, footer, legal strip and page CSS are copied from the hub page
 * (commercial/index.html) every run, so a site-wide nav/footer sweep only has
 * to touch the hub and these pages follow on the next generate.
 *
 * Rules (Mike, 2026-11-21): no rate, LTV or DSCR minimum on any commercial
 * page (priced case by case), nothing in rates.json, no investor or capital
 * partner names. The generator refuses to write a page that breaks the first.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SITE = 'https://slacapital.ai';
const PORTAL = 'https://portal.slacapital.ai/commercial';
const { types } = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'commercial-types.json'), 'utf8'));
const hub = fs.readFileSync(path.join(ROOT, 'commercial', 'index.html'), 'utf8');

function block(src, start, end) {
  const i = src.indexOf(start);
  const j = i < 0 ? -1 : src.indexOf(end, i);
  if (i < 0 || j < 0) throw new Error('hub page is missing ' + start);
  return src.slice(i, j + end.length);
}
const STYLE = block(hub, '<style>', '</style>');
const LEGAL = block(hub, '<div class="legal-strip">', '</div>\n  </div>');
const NAV = block(hub, '<nav class="site-nav">', '</nav>');
const FOOTER = block(hub, '<footer class="site-footer">', '</footer>');

const esc = (s) => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const json = (o) => JSON.stringify(o).replace(/</g, '\\u003c');
const lower = (n) => n.toLowerCase();

const CHIP = {
  'multifamily': 'Multi-family', 'mixed-use': 'Mixed-use', 'retail': 'Retail & strip centers', 'office': 'Office',
  'light-industrial': 'Light industrial', 'warehouse': 'Warehouse', 'self-storage': 'Self-storage',
  'mobile-home-parks': 'Mobile home parks', 'commercial-condos': 'Commercial condos', 'automotive': 'Automotive',
  'restaurants-bars': 'Restaurants & bars', 'day-care': 'Day care', 'bulk-residential': 'Bulk residential',
};

function page(t) {
  const url = `${SITE}/commercial/${t.slug}/`;
  const others = types.filter((o) => o.slug !== t.slug)
    .map((o) => `<a href="/commercial/${o.slug}/">${esc(CHIP[o.slug] || o.name)}</a>`).join('');

  const schemaLoan = {
    '@context': 'https://schema.org', '@type': 'LoanOrCredit',
    name: `${t.name} Loans`, url,
    provider: { '@type': 'FinancialService', name: 'SLA Capital', alternateName: 'Sir Lends A Lot LLC', url: SITE },
    loanType: `Commercial real estate loan for ${lower(t.name)} property`,
    amount: { '@type': 'MonetaryAmount', currency: 'USD', maxValue: 20000000 },
    areaServed: { '@type': 'Country', name: 'United States' },
    description: `${t.lede} Commercial Bridge Loans up to $20,000,000 and Commercial DSCR Loans up to $3,000,000, reviewed and priced case by case. Purchase, refinance and cash-out; investor and owner-occupied.`,
  };
  const schemaFaq = {
    '@context': 'https://schema.org', '@type': 'FAQPage',
    mainEntity: t.faqs.map((f) => ({ '@type': 'Question', name: f.q, acceptedAnswer: { '@type': 'Answer', text: f.a } })),
  };
  const schemaCrumbs = {
    '@context': 'https://schema.org', '@type': 'BreadcrumbList',
    itemListElement: [
      { '@type': 'ListItem', position: 1, name: 'Home', item: `${SITE}/` },
      { '@type': 'ListItem', position: 2, name: 'Commercial Loans', item: `${SITE}/commercial/` },
      { '@type': 'ListItem', position: 3, name: `${t.name} Loans`, item: url },
    ],
  };

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <!-- GENERATED by scripts/generate-commercial-pages.mjs from data/commercial-types.json. Edit the data, not this file. -->
  <title>${esc(t.title)}</title>
  <meta name="description" content="${esc(t.description)}" />
  <link rel="canonical" href="${url}" />

  <link rel="icon" type="image/x-icon" href="/assets/favicon.ico" />
  <link rel="icon" type="image/png" sizes="any" href="/assets/favicon.png" />
  <link rel="apple-touch-icon" href="/assets/favicon.png" />

  <meta property="og:type" content="website" />
  <meta property="og:site_name" content="SLA Capital" />
  <meta property="og:title" content="${esc(t.title)}" />
  <meta property="og:description" content="${esc(t.description)}" />
  <meta property="og:url" content="${url}" />
  <meta property="og:image" content="${SITE}/assets/og/commercial-${t.slug}.png" />
  <meta name="twitter:card" content="summary_large_image" />

  <link rel="stylesheet" href="/assets/brand.css" />
  ${STYLE}
  <style>
    .checks { list-style: none; padding: 0; margin: 0; }
    .checks li { position: relative; padding: 9px 0 9px 30px; border-top: 1px dashed #ece6e2; color: var(--muted); }
    .checks li:first-child { border-top: 0; }
    .checks li::before { content: '\\2713'; position: absolute; left: 6px; top: 9px; color: var(--primary); font-weight: 700; }
    .types a:hover { border-color: var(--primary); color: var(--primary); }
  </style>

  <script type="application/ld+json">${json(schemaLoan)}</script>
  <script type="application/ld+json">${json(schemaFaq)}</script>
  <script type="application/ld+json">${json(schemaCrumbs)}</script>
</head>
<body>

  ${LEGAL}

  ${NAV}

  <div class="container" style="padding-top:16px;font-size:14px;color:var(--muted)">
    <a href="/" style="color:var(--muted)">Home</a> · <a href="/commercial/" style="color:var(--muted)">Commercial Loans</a> · <span>${esc(t.name)} Loans</span>
  </div>

  <section class="section" style="padding-top:48px;padding-bottom:56px">
    <div class="container" style="max-width:820px">
      <div class="eyebrow">Commercial Loans · ${esc(t.name)}</div>
      <h1 style="font-size:44px;line-height:1.15;margin-bottom:20px">${esc(t.h1)}</h1>
      <p class="lede">${esc(t.lede)}</p>
      <div style="display:flex;gap:14px;flex-wrap:wrap;margin-top:24px">
        <a href="${PORTAL}" class="btn btn-primary btn-lg">Apply for a Commercial Loan</a>
        <a href="mailto:apply@slacapital.com" class="btn btn-ghost btn-lg">Talk to a Loan Officer</a>
      </div>
    </div>
  </section>

  <section class="section section-tinted">
    <div class="container" style="max-width:1000px">
      <h2 style="text-align:center;margin-bottom:12px">How we finance ${esc(lower(t.name))} property</h2>
      <p style="text-align:center;color:var(--muted);margin-bottom:40px">Purchase, refinance and cash-out · Investor and owner-occupied · Reviewed and priced case by case</p>
      <div class="grid grid-2">
        <div class="card prod">
          <div class="chip" style="margin-bottom:16px;align-self:flex-start">Short-term</div>
          <h3 style="margin:0">Commercial Bridge Loan</h3>
          <div class="limit">Up to $20,000,000</div>
          <p style="color:var(--muted);margin-top:0;margin-bottom:24px">${esc(t.bridgeUse)}</p>
          <a href="${PORTAL}?type=bridge" class="btn btn-primary">Apply for a Bridge Loan</a>
        </div>
        <div class="card prod">
          <div class="chip" style="margin-bottom:16px;align-self:flex-start">Long-term</div>
          <h3 style="margin:0">Commercial DSCR Loan</h3>
          <div class="limit">Up to $3,000,000</div>
          <p style="color:var(--muted);margin-top:0">${esc(t.dscrUse)}</p>
          <p style="color:var(--muted);margin-top:0;margin-bottom:24px;font-size:15px">5-year hybrid or 15, 25 and 30-year fixed · full doc, lite doc, bank statement and no-doc options.</p>
          <a href="${PORTAL}?type=dscr" class="btn btn-primary">Apply for a DSCR Loan</a>
        </div>
      </div>
    </div>
  </section>

  <section class="section">
    <div class="container" style="max-width:1000px">
      <div class="grid grid-2" style="gap:40px">
        <div>
          <div class="eyebrow">Underwriting</div>
          <h2 style="font-size:28px;margin-bottom:16px">What we look at on a ${esc(lower(t.name))} loan</h2>
          <ul class="checks">
${t.underwriting.map((u) => `            <li>${esc(u)}</li>`).join('\n')}
          </ul>
        </div>
        <div>
          <div class="eyebrow">Scenarios</div>
          <h2 style="font-size:28px;margin-bottom:16px">Common ${esc(lower(t.name))} deals we see</h2>
          <ul class="checks">
${t.scenarios.map((s) => `            <li>${esc(s)}</li>`).join('\n')}
          </ul>
        </div>
      </div>
    </div>
  </section>

  <section class="section section-tinted">
    <div class="container" style="max-width:820px">
      <div style="text-align:center;margin-bottom:40px">
        <div class="eyebrow">${esc(t.name)} loan FAQ</div>
        <h2>Common questions about ${esc(lower(t.name))} loans.</h2>
      </div>
${t.faqs.map((f, i) => `      <details class="card"${i < t.faqs.length - 1 ? ' style="margin-bottom:12px"' : ''}>
        <summary style="font-weight:600;font-size:18px;cursor:pointer;color:var(--secondary)">${esc(f.q)}</summary>
        <p style="margin-top:12px;color:var(--muted)">${esc(f.a)}</p>
      </details>`).join('\n')}
    </div>
  </section>

  <section class="section">
    <div class="container" style="max-width:900px;text-align:center">
      <div class="eyebrow">Other property types</div>
      <h2 style="margin-bottom:24px">We also finance</h2>
      <div class="types">${others}</div>
      <p style="margin-top:24px"><a href="/commercial/" style="font-weight:600">All commercial loans →</a></p>
    </div>
  </section>

  <section class="section section-dark">
    <div class="container" style="text-align:center;max-width:720px">
      <div class="eyebrow" style="color:var(--highlight)">Get started</div>
      <h2 style="color:#fff">Have a ${esc(lower(t.name))} deal?</h2>
      <p style="color:rgba(255,255,255,0.78);font-size:19px;margin-bottom:32px">Tell us about the property and what you want to do with it. A loan officer reviews it and comes back with terms.</p>
      <div style="display:flex;gap:14px;justify-content:center;flex-wrap:wrap">
        <a href="${PORTAL}" class="btn btn-primary btn-lg">Apply for a Commercial Loan</a>
        <a href="mailto:apply@slacapital.com" class="btn btn-ghost btn-lg" style="color:#fff;border-color:#fff">apply@slacapital.com</a>
      </div>
    </div>
  </section>

  ${FOOTER}

</body>
</html>
`;
}

// Guard: commercial pages never carry a rate, LTV or DSCR minimum. CSS percentages
// (width/height: 100%) are fine, so only the visible text and schema are checked.
const BANNED = /\b\d+(\.\d+)?\s?%|\bLTV\b|\bLTC\b|loan-to-value|loan-to-cost|DSCR (minimum|of 1\.|1\.\d)/i;
let written = 0;
for (const t of types) {
  const html = page(t);
  const text = html.replace(/<style>[\s\S]*?<\/style>/, '').replace(/style="[^"]*"/g, '');
  const hit = text.match(BANNED);
  if (hit) throw new Error(`${t.slug}: banned commercial term "${hit[0]}"`);
  const dir = path.join(ROOT, 'commercial', t.slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), html);
  written++;
}
console.log(`✓ ${written} commercial property-type pages written -> commercial/<slug>/`);
